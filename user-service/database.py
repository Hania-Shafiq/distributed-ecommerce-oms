import os
from dotenv import load_dotenv
from sqlalchemy import create_engine
from sqlalchemy.orm import declarative_base, sessionmaker

# ---------------------------------------------------------------------------
# 1. Load Environment Variables
# ---------------------------------------------------------------------------
# Load settings from .env file into the environment.
# This prevents hardcoding credentials and connection strings in source code.
load_dotenv()

# Read the PostgreSQL connection URL from the environment.
# Default fallback is provided matching the project specification if .env is missing.
DATABASE_URL = os.getenv(
    "DATABASE_URL",
    "postgresql://postgres:postgres@localhost:5433/users_db"
)

# ---------------------------------------------------------------------------
# 2. SQLAlchemy Engine & Connection Pool
# ---------------------------------------------------------------------------
# The engine acts as the central interface to the PostgreSQL database, managing
# a connection pool and executing raw SQL statements generated by the ORM.
DB_POOL_SIZE = int(os.getenv("DB_POOL_SIZE", "25"))
DB_MAX_OVERFLOW = int(os.getenv("DB_MAX_OVERFLOW", "15"))
DB_POOL_TIMEOUT = int(os.getenv("DB_POOL_TIMEOUT", "30"))

engine = create_engine(
    DATABASE_URL,
    pool_pre_ping=True,  # Automatically check connection liveness before executing queries
    pool_size=DB_POOL_SIZE,
    max_overflow=DB_MAX_OVERFLOW,
    pool_timeout=DB_POOL_TIMEOUT,
)

# ---------------------------------------------------------------------------
# 3. Session Factory
# ---------------------------------------------------------------------------
# SessionLocal is a factory that generates new Session objects for database transactions.
# autocommit=False ensures transactions are explicitly controlled (commit/rollback).
# autoflush=False avoids premature flushes before commit.
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

# ---------------------------------------------------------------------------
# 4. Declarative Base
# ---------------------------------------------------------------------------
# Base class for all SQLAlchemy ORM models in models.py.
Base = declarative_base()

# ---------------------------------------------------------------------------
# 5. Dependency for FastAPI Endpoints
# ---------------------------------------------------------------------------
def get_db():
    """
    FastAPI dependency that provides a transactional database session per request.
    Yields the session and ensures it is safely closed in the `finally` block
    even if an exception is raised during request processing.
    """
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
