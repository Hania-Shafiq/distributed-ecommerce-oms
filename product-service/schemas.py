# schemas.py
# ─────────────────────────────────────────────────────────────────────────────
# Pydantic schemas define the *shape* of data that travels over the HTTP wire:
#   • What the client sends  (request body)
#   • What the server returns (response body)
#
# These are completely separate from the SQLAlchemy models in models.py.
# Keeping them separate is a best-practice: it lets you expose only the fields
# you want (e.g., hide internal flags) and validate input independently of the DB.
# ─────────────────────────────────────────────────────────────────────────────

from pydantic import BaseModel, Field
from typing import Optional


# ── ProductBase ───────────────────────────────────────────────────────────────
# Contains all fields that are shared between "create" and "update" schemas.
# We define them once here and reuse via inheritance to avoid duplication.
class ProductBase(BaseModel):
    name: str = Field(
        ...,                          # ... means "required" in Pydantic
        min_length=1,
        max_length=255,
        description="Product display name",
    )
    category: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="Product category (e.g. 'Electronics')",
    )
    price: float = Field(
        ...,
        gt=0,                         # gt=0 → must be greater than 0; price can't be free or negative
        description="Unit price in USD",
    )
    description: Optional[str] = Field(
        default=None,                 # Optional → client may omit this field entirely
        description="Detailed product description (used for Elasticsearch search)",
    )
    stock_quantity: int = Field(
        default=0,
        ge=0,                         # ge=0 → stock can't be negative
        description="Number of units in stock",
    )


# ── ProductCreate ─────────────────────────────────────────────────────────────
# Schema used for POST /products.
# Inherits all fields from ProductBase with no additions needed.
# Having a separate class (vs using ProductBase directly) keeps the door open
# for future create-only fields (e.g. a one-time discount code).
class ProductCreate(ProductBase):
    pass


# ── ProductUpdate ─────────────────────────────────────────────────────────────
# Schema used for PUT /products/{id}.
# Every field is Optional here so the client can send a *partial* update
# (i.e., only the fields they want to change).
# Without Optional, forgetting to include 'name' in the body would cause a 422.
class ProductUpdate(BaseModel):
    name:           Optional[str]   = Field(default=None, max_length=255)
    category:       Optional[str]   = Field(default=None, max_length=100)
    price:          Optional[float] = Field(default=None, gt=0)
    description:    Optional[str]   = None
    stock_quantity: Optional[int]   = Field(default=None, ge=0)


# ── ProductResponse ───────────────────────────────────────────────────────────
# Schema used in all *response* bodies (GET, POST, PUT).
# Extends ProductBase and adds the `id` field (auto-generated by the DB;
# we never accept it from the client, but we always return it).
#
# model_config with from_attributes=True (Pydantic v2 syntax, replaces
# orm_mode=True from v1) tells Pydantic that it can build this model from
# a SQLAlchemy ORM object by reading attributes — not just from a plain dict.
# Without this, FastAPI's response_model serialization would fail.
class ProductResponse(ProductBase):
    id: int

    model_config = {"from_attributes": True}
